import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { assertNoRetiredStreamProbe } from './retired-stream-probe.mjs';
import { assertNoRetiredHTTPPush } from './retired-http-push.mjs';
import { assertNoRetiredControls } from './retired-controls.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const [backend, ref] = process.argv.slice(2);
assert.ok(backend && ref, 'Usage: sync-source-stream-contract.mjs <backend> <commit|--worktree>');
const git = (...args) => execFileSync('git', ['-C', backend, ...args], { maxBuffer: 64 << 20 });
const preview = ref === '--worktree';
const revision = git('rev-parse', `${preview ? 'HEAD' : ref}^{commit}`).toString().trim();
const upstream = path => preview ? readFileSync(resolve(backend, path)) : git('show', `${revision}:${path}`);
const local = path => readFileSync(resolve(root, path));
const digest = value => createHash('sha256').update(value).digest('hex');
const json = value => Buffer.from(JSON.stringify(value, null, 2) + '\n');
const selected = name => /^(source|stream)/.test(name);
const sourcePaths = {
  'contracts/uns-v2/contract.json': 'service/unssvr/internal/domain/unsv2/contract_generated.go',
  'contracts/uns-v2/manifest.json': 'share/unscontract/manifest.json',
  'contracts/uns-v2/cloud-support.json': 'share/unscontract/cloud-support.json',
  'contracts/uns-v2/registry_generated.go': 'share/unscontract/registry_generated.go',
  'contracts/uns-v2/source-protocols.json': 'share/unscontract/source-protocols.json',
};
const lock = JSON.parse(local('contracts/upstream.json'));
const provenance = JSON.parse(local('contracts/uns-v2/provenance.json'));
const previous = provenance.schemaUpdates?.find(item => item.scope === 'source-stream-public');
function closure(doc, operations) {
  const names = new Set();
  const pending = operations.flatMap(op => [op.request, op.response]).filter(Boolean);
  function visit(value) {
    if (!value || typeof value !== 'object') return;
    if (value.$ref?.startsWith('#/components/schemas/')) pending.push(value.$ref.split('/').at(-1));
    Object.values(value).forEach(visit);
  }
  while (pending.length) {
    const name = pending.pop();
    if (names.has(name)) continue;
    assert.ok(doc.schemas[name], `Missing schema ${name}`);
    names.add(name); visit(doc.schemas[name]);
  }
  return names;
}
const outputs = new Map();
const update = { scope: 'source-stream-public', repository: 'FREEZONEX/Tier0-Backend', revision,
  sourceKind: preview ? 'working-tree-preview' : 'committed', inputs: {}, schemas: [] };
for (const [path, sourcePath] of Object.entries(sourcePaths)) {
  const before = local(path);
  assert.equal(digest(before), lock.inputs[path].sha256, `Unsynced input ${path}`);
  const raw = upstream(sourcePath);
  assertNoRetiredStreamProbe(raw.toString(), sourcePath);
  assertNoRetiredHTTPPush(raw.toString(), sourcePath);
  assertNoRetiredControls(raw.toString(), sourcePath);
  let after;
  if (path.endsWith('registry_generated.go')) {
    const oldLines = before.toString().split('\n');
    const newLines = raw.toString().split('\n');
    const name = line => line.match(/\{Name: "([^"]+)"/)?.[1];
    const rows = [...oldLines.filter(line => name(line) && !selected(name(line))), ...newLines.filter(line => name(line) && selected(name(line)))];
    after = Buffer.from('// Code generated by scripts/sync-source-stream-contract.mjs. DO NOT EDIT.\npackage unscontract\n\nvar operations = []Operation{\n' + rows.join('\n') + '\n}\n');
  } else if (path.endsWith('source-protocols.json')) after = raw;
  else {
    const current = JSON.parse(before);
    const incoming = path.endsWith('/contract.json')
      ? JSON.parse(JSON.parse(raw.toString().match(/^const ContractJSON = ("(?:\\[\s\S]|[^"\\])*")\r?$/m)[1]))
      : JSON.parse(raw);
    if (incoming.cloudContractRevision) update.sourceContractRevision = incoming.cloudContractRevision;
    const operations = incoming.operations.filter(op => selected(op.name));
    if (current.schemas) {
      const retired = closure(current, current.operations.filter(op => selected(op.name)));
      const retained = closure(current, current.operations.filter(op => !selected(op.name)));
      const required = closure(incoming, operations);
      for (const name of retired) if (!retained.has(name) && !required.has(name)) delete current.schemas[name];
      for (const name of required) current.schemas[name] = incoming.schemas[name];
      update.schemas = [...new Set([...update.schemas, ...required])].sort();
    }
    current.operations = [...current.operations.filter(op => !selected(op.name)), ...operations];
    after = path.endsWith('/contract.json') ? Buffer.from(JSON.stringify(current) + '\n') : json(current);
  }
  outputs.set(path, after);
  update.inputs[path] = { path: sourcePath, sourceSHA256: digest(raw), baseSHA256: previous?.inputs[path]?.baseSHA256 ?? digest(before), resultSHA256: digest(after) };
  lock.inputs[path] = { ...lock.inputs[path], sha256: digest(after) };
}
// Supersede old scoped overlays for these same inputs; unrelated inputs stay pinned.
const updates = (provenance.schemaUpdates || []).filter(item => !['source-stream-acquisition', 'source-stream-public'].includes(item.scope));
updates.push(update);
provenance.schemaUpdates = updates; lock.schemaUpdates = updates;
provenance.sourceDerivedContractSHA256 = digest(outputs.get('contracts/uns-v2/contract.json'));
provenance.note = 'Source/Stream public operations and transitive schemas are synchronized separately; unrelated operation contracts retain their pinned base.';
outputs.set('contracts/upstream.json', json(lock));
outputs.set('contracts/uns-v2/provenance.json', json(provenance));
for (const [path, data] of outputs) writeFileSync(resolve(root, path), data);
console.log(`Synced Source/Stream public contract ${revision} (${update.sourceKind}), ${update.schemas.length} schemas.`);
